from fastapi import APIRouter, HTTPException, Depends
from sqlalchemy.orm import Session
from app.database import get_db
from app.models.recommendation import Recommendation
from app.models.forecast import Forecast
from app.models.product import Product
from app.models.inventories import Inventory
from app.schemas.recommendation import RecommendationResponse, RecommendationCreate

router = APIRouter(prefix="/recommendations", tags=["recommendations"])

@router.get("/", response_model=list[RecommendationResponse])
def get_recommendations(db: Session = Depends(get_db)):
    recommendations = db.query(Recommendation).all()
    if not recommendations:
        raise HTTPException(status_code=404, detail="No recommendations found")
    return recommendations

#just for testing, in production this would be generated by the ML model and not created via API
# it should be chaneg to RecommendationCreate and not return the reason, as that is only for internal use to explain the recommendation to the user and should not be stored in the database
@router.post("/", response_model=RecommendationResponse)
def create_recommendation(recommendation: RecommendationCreate, db: Session = Depends(get_db)):
    db_recommendation = Recommendation(
        product_id=recommendation.product_id,
        recommended_quantity=recommendation.recommended_quantity,
        reason=recommendation.reason,
    )
    db.add(db_recommendation)
    db.commit()
    db.refresh(db_recommendation)
    return db_recommendation

@router.post("/generate/{product_id}", response_model=RecommendationResponse)
def generate_recommendation(product_id: int, db: Session = Depends(get_db)):
    product = db.query(Product).filter(Product.id == product_id).first()
    if not product:
        raise HTTPException(status_code=404, detail="Product not found")
    
    forecast = db.query(Forecast).filter(Forecast.product_id == product_id).order_by(Forecast.forecast_date.desc()).first()
    inventory = db.query(Inventory).filter(Inventory.product_id == product_id).first()
    
    if not forecast or not inventory:
        raise HTTPException(status_code=404, detail="Forecast or Inventory data not found for the product")
    
    if inventory.current_stock <= product.reorder_threshold:
        recommended_quantity = max(int(forecast.predicted_demand - inventory.current_stock), 0)
    else:
        recommended_quantity = 0

    reason = f"Current inventory is {inventory.current_stock}, forecasted demand is {forecast.predicted_demand}. Recommended quantity is {recommended_quantity}."    
    db_recommendation = Recommendation(
        product_id=product_id,
        recommended_quantity=recommended_quantity,
        reason=reason,
    )
    db.add(db_recommendation)
    db.commit()
    db.refresh(db_recommendation)
    return db_recommendation

@router.post("/generate_all", response_model=list[RecommendationResponse])
def generate_recommendations_for_all_products(db: Session = Depends(get_db)):
    products = db.query(Product).all()
    recommendations = []
    
    for product in products:
        existing_recommendations = db.query(Recommendation).filter(Recommendation.product_id==product.id).first()
        if existing_recommendations:
            continue# Skip if recommendation already exists for the product
        forecast = db.query(Forecast).filter(Forecast.product_id == product.id).order_by(Forecast.forecast_date.desc()).first()
        inventory = db.query(Inventory).filter(Inventory.product_id == product.id).first()
        
        if not forecast or not inventory:
            continue
        
        if inventory.current_stock <= product.reorder_threshold:
            recommended_quantity = max(int(forecast.predicted_demand) - inventory.current_stock,0)
        else:
            continue  # Skip if inventory is above threshold, no recommendation needed

        reason = f"Current inventory is {inventory.current_stock}, forecasted demand is {forecast.predicted_demand}. Recommended quantity is {recommended_quantity}."    
        db_recommendation = Recommendation(
            product_id=product.id,
            recommended_quantity=recommended_quantity,
            reason=reason,
        )
        db.add(db_recommendation)
        recommendations.append(db_recommendation)
    
    db.commit()
    for r in recommendations:
        db.refresh(r)
    
    return recommendations